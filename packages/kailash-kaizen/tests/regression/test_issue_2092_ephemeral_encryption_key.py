@pytest.mark.regression
def test_environment_variable_supplies_the_key_with_no_code_change():
    """The wiring the error message names must actually work.

    The assertion is that the provider derives THAT key, not merely that it
    round-trips: a provider that ignored the variable and generated its own key
    would also encrypt and decrypt its own data happily, so a round-trip alone
    cannot tell the two apart.

    Falsifying result if the read were absent: the constructor raises, or the
    resolved key differs from the one the passphrase derives.
    """
    os.environ["KAIZEN_ENCRYPTION_KEY"] = CONFIGURED_PASSPHRASE
    try:
        provider = EncryptionProvider()
        assert provider.decrypt(provider.encrypt("hello")) == "hello"
        assert provider.key == EncryptionProvider(key=CONFIGURED_PASSPHRASE).key, (
            "The provider did not derive its key from the environment variable; "
            "it used its own value, so the variable named in the error message "
            "is not actually wired."
        )
    finally:
        del os.environ["KAIZEN_ENCRYPTION_KEY"]


