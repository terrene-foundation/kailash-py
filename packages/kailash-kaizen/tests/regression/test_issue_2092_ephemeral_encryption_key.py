@pytest.mark.regression
def test_two_providers_from_the_same_configured_key_interoperate():
    """The multi-replica property, stated positively (AC of #2092).

    A value encrypted by one replica MUST be readable by another configured from
    the same source. Before the fix each replica generated its own key and this
    failed with ``InvalidTag``.

    Falsifying result if the property were absent: ``InvalidTag`` on decrypt.
    """
    replica_a = EncryptionProvider(key=CONFIGURED_RAW_KEY)
    replica_b = EncryptionProvider(key=CONFIGURED_RAW_KEY)

    sealed = replica_a.encrypt({"ssn": "123-45-6789"})
    assert replica_b.decrypt(sealed) == {"ssn": "123-45-6789"}


@pytest.mark.regression
def test_two_providers_from_the_same_passphrase_interoperate_across_restarts():
    """A passphrase must derive the SAME key every time, or it is not durable.

    A per-process random salt would make each derivation unique and reproduce
    the very defect this issue is about, one layer down.

    Falsifying result if derivation were salted per process: ``InvalidTag``.
    """
    os.environ["KAIZEN_ENCRYPTION_KEY"] = CONFIGURED_PASSPHRASE
    try:
        before_restart = EncryptionProvider()
        sealed = before_restart.encrypt("survives")
        after_restart = EncryptionProvider()
        assert after_restart.decrypt(sealed) == "survives"
    finally:
        del os.environ["KAIZEN_ENCRYPTION_KEY"]


@pytest.mark.regression
def test_key_manager_versions_are_distinct_yet_survive_a_restart():
    """Rotation must produce a DIFFERENT key per version, and a DURABLE one.

    Two managers configured from the same master key model the same service
    before and after a restart: data written under version 1 must still read
    back, and version 2 must not be the same key as version 1 (or rotation
    would be cosmetic).

    Falsifying result: ``InvalidTag`` across managers (not durable), or equal
    per-version keys (rotation does nothing).
    """
    before_restart = KeyManager(key=CONFIGURED_RAW_KEY)
    sealed_v1 = before_restart.encrypt("v1 data")
    before_restart.rotate_key(2)
    sealed_v2 = before_restart.encrypt("v2 data")

    assert (
        before_restart.keys[1].key != before_restart.keys[2].key
    ), "Rotation produced the same key material for both versions."

    after_restart = KeyManager(key=CONFIGURED_RAW_KEY)
    after_restart.rotate_key(2)
    assert after_restart.decrypt(sealed_v1) == "v1 data"
    assert after_restart.decrypt(sealed_v2) == "v2 data"


@pytest.mark.regression
def test_field_encryptor_round_trips_when_configured():
    """Negative control: the configured path must keep working.

    Falsifying result: a change that "fixed" the defect by breaking encryption
    outright would fail here while passing every raise-assertion above.
    """
    encryptor = FieldEncryptor(sensitive_fields=["ssn"], key=CONFIGURED_RAW_KEY)
    sealed = encryptor.encrypt_fields({"ssn": "123-45-6789", "name": "Kim"})

    assert sealed["ssn"].startswith("encrypted:")
    assert sealed["name"] == "Kim", "Non-sensitive fields must be untouched."

    reader = FieldEncryptor(sensitive_fields=["ssn"], key=CONFIGURED_RAW_KEY)
    assert reader.decrypt_fields(sealed)["ssn"] == "123-45-6789"


