"""Regression tests for issue #2092 — kaizen EncryptionProvider invented its AES key.

Before the fix, ``EncryptionProvider(key=None)`` generated a fresh AES-256-GCM
key via ``AESGCM.generate_key`` and continued **entirely silently** — no error,
no warning, not even an INFO line. The key lived only inside that process, so
anything encrypted under it was unrecoverable after the process exited, and in a
multi-replica deployment a value written by replica A could not be read by
replica B. Because nothing was logged, the first symptom was unreadable data
with nothing in the logs pointing at why.

The default propagated through two wrappers, which is how it stayed hidden:

- ``KeyManager.__init__`` took no key parameter at all and called
  ``EncryptionProvider()`` bare for every key version, so ``re_encrypt`` — the
  documented migration path — destroyed the pre-rotation data too.
- ``FieldEncryptor(sensitive_fields=[...], key=None)`` forwarded ``None``
  straight through, so a call that reads as fully configured silently got a
  throwaway key for PII.

Third instance of the same class as #2041 (``SecretManager``, PR #2063) and
#2083 (``JWTAuthManager``), each using a different generator.

Each test docstring names the result it would produce if the property under test
were absent, so a green here is readable as evidence rather than as a pass.
"""

from __future__ import annotations

import logging
import os
from pathlib import Path

import pytest

from kaizen.security import encryption as encryption_module
from kaizen.security.encryption import (
    MIN_PASSPHRASE_LENGTH,
    EncryptionKeyNotConfiguredError,
    EncryptionProvider,
    FieldEncryptor,
    KeyManager,
)

#: A passphrase an operator would plausibly configure.
CONFIGURED_PASSPHRASE = "a-configured-kaizen-encryption-passphrase"

#: A raw 32-byte key, the other accepted shape.
CONFIGURED_RAW_KEY = b"0123456789abcdef0123456789abcdef"


@pytest.fixture(autouse=True)
def _reset_one_time_signal():
    """Clear the ``lru_cache``d one-time signal between tests.

    Without this only the first test to trigger the signal could observe it, and
    every later assertion would read a cache hit as "no signal was emitted".
    """
    warn = getattr(encryption_module, "_warn_ephemeral_encryption_key", None)
    if warn is not None and hasattr(warn, "cache_clear"):
        warn.cache_clear()
    yield
    if warn is not None and hasattr(warn, "cache_clear"):
        warn.cache_clear()


